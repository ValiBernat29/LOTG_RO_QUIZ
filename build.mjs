import { readFile, writeFile } from 'node:fs/promises';
import { findLawReference, validateLawLibrary } from './dist/laws-ro.js';
import {writeLawAudit} from './tools/law-audit.mjs';
const input = new URL('../lotg_ro_questions.json', import.meta.url);
const output = new URL('dist/questions.json', import.meta.url);
// Locally use the scraper's Romanian bank. On Netlify the repository starts
// at quiz-web, so use the validated question bank already committed in dist.
let json;
try {
  json = await readFile(input, 'utf8');
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  json = await readFile(output, 'utf8');
}
const questions = JSON.parse(json.replace(/^\uFEFF/, ''));
const ruleCorrections = JSON.parse(await readFile(new URL('editorial/rule-corrections.json', import.meta.url), 'utf8'));
for (const correction of ruleCorrections.rows) {
  const q = questions.find(q=>q.id===correction.id);
  if (!q || q.questionRo!==correction.questionRo || q.correctOption!==correction.after.correctOption ||
      JSON.stringify(q.options)!==JSON.stringify(correction.after.options)) throw new Error(`Rule correction drift: ${correction.id}`);
}
await writeFile(new URL('dist/rule-corrections.js', import.meta.url),
  '// Generated by build.mjs; semantic corrections are applied after wording repairs.\nexport const RULE_CORRECTIONS = '+JSON.stringify(ruleCorrections.rows)+';\n','utf8');
const ids = new Set();
for (const q of questions) {
  if (!Number.isInteger(q.id) || ids.has(q.id) || !q.questionRo || !q.options ||
      Object.keys(q.options).join('') !== 'ABCD' || !q.options[q.correctOption] ||
      q.lawNumber < 1 || q.lawNumber > 17) throw new Error(`Întrebare invalidă: ${q.id}`);
  ids.add(q.id);
}
const library = validateLawLibrary(JSON.parse(await readFile(new URL('dist/laws-ro.json', import.meta.url), 'utf8')));
const questionRevisions = JSON.parse(await readFile(new URL('editorial/question-revisions.json', import.meta.url), 'utf8'));
for (const revision of questionRevisions.rows) {
  const question = questions.find(q => q.id === revision.id);
  if (!question || question.questionRo !== revision.afterQuestionRo ||
      question.options[question.correctOption] !== revision.correctText) {
    throw new Error(`Question context revision drift: ${revision.id}`);
  }
}
await writeFile(new URL('dist/question-revisions.js', import.meta.url),
  '// Generated by build.mjs from the reviewed question context changes.\nexport const QUESTION_REVISIONS = ' +
  JSON.stringify(questionRevisions.rows.map(({id,beforeQuestionRo,afterQuestionRo,correctText}) =>
    ({id,beforeQuestionRo,afterQuestionRo,correctText}))) + ';\n', 'utf8');
const scan = JSON.parse(await readFile(new URL('laws/official-ro-2026-27.json', import.meta.url), 'utf8'));
for (const excerpt of library.excerpts.filter(e => e.source.kind === 'official-ro-scan')) {
  const reviewed = scan.excerpts.find(e => e.id === excerpt.id);
  if (JSON.stringify(excerpt) !== JSON.stringify(reviewed)) throw new Error(`Scan transcription drift: ${excerpt.id}`);
}
const photos = JSON.parse(await readFile(new URL('laws/official-ro-photos-2026-27.json', import.meta.url), 'utf8'));
if (JSON.stringify(library.photoSources)!==JSON.stringify(photos.sources)) throw new Error('Photo source registration drift');
for (const excerpt of library.excerpts.filter(e => e.source.kind === 'official-ro-photo')) {
  const reviewed = photos.excerpts.find(e => e.id === excerpt.id);
  if (JSON.stringify(excerpt)!==JSON.stringify(reviewed)) throw new Error(`Photo transcription drift: ${excerpt.id}`);
}
for (const reference of library.references) {
  const seed = questions.find(q => q.id === reference.seedId);
  if (!seed || !findLawReference({...library, references:[reference]}, seed)) {
    throw new Error(`Referință de reverificat după modificarea întrebării ${reference.seedId}`);
  }
}
await writeFile(output, JSON.stringify(questions), 'utf8');
const revisions = JSON.parse(await readFile(new URL('editorial/answer-revisions.json', import.meta.url), 'utf8'));
for (const revision of revisions.rows) {
  const question = questions.find(q => q.id === revision.id);
  if (!question || question.questionRo !== (revision.currentQuestionRo ?? revision.questionRo) || question.correctOption !== (revision.currentCorrectOption ?? revision.correctOption) ||
      Object.keys(revision.after).some(k => question.options[k] !== (revision.currentOptions ?? revision.after)[k])) {
    throw new Error(`Editorial revision drift: ${revision.id}`);
  }
}
await writeFile(new URL('dist/option-revisions.js', import.meta.url),
  '// Generated by build.mjs from the reviewed editorial changes.\nexport const OPTION_REVISIONS = ' + JSON.stringify(revisions.rows) + ';\n', 'utf8');
const coverage=await writeLawAudit(questions,library,JSON.parse(await readFile(new URL('laws/references.json',import.meta.url),'utf8')));
// Regenerate the rule-change warning queue; this audit never edits answer keys.
await import('./tools/rule-change-audit.mjs');
console.log(`Pregătite ${questions.length} întrebări pentru quiz.`);
console.log(`Pasaje în română: ${coverage.summary.associatedRecords}/${questions.length} întrebări asociate; ${coverage.summary.verifiedRecords} verificate pentru ${library.targetEdition}, ${coverage.summary.legacyRecords} de reverificat din ${library.edition}.`);
